-- FALAFEL BATACHANA — PARCEL MODULE — parcel_01_tables.sql (GATE 03B)
-- Server-only parcel tables: public.parcel_requests + public.parcel_events, their internal triggers,
-- RLS (no policies) and least-privilege grants.
--
-- REVIEW ONLY — NOT EXECUTED. Run manually, first in an isolated staging database, then (after approval)
-- in Production. Order: parcel_01 → parcel_02 → (optional, separately approved) parcel_03 → parcel_99_verify.
--
-- Touches NO existing table, policy, grant, trigger or function. The only interaction with existing objects:
--   * two FOREIGN KEYs (→ public.orders, → public.branches): creating them takes a brief
--     SHARE ROW EXCLUSIVE lock on orders / branches (bounded by lock_timeout below);
--   * the parcel triggers READ public.orders (never write it).
--
-- Rules enforced here (independent of application code):
--   * at most one parcel request per order; only for a DELIVERY order still in status 'received';
--   * branch_id is always copied from the saved order (no hardcoded branch, no client-supplied branch);
--   * tracking reference: ASCII letters/digits + space . _ / # -  (4–40 chars, no URLs possible);
--     tracking_key = UPPER(ref without non-alphanumerics), 4–40 chars — generated by the database;
--   * no two ACTIVE parcel requests with the same (branch, tracking_key) — carrier deliberately NOT part of
--     the key (free-text carrier cannot be trusted as identity; conservative choice);
--   * explicit parcel status machine; operational timestamps stamped by the database;
--   * every insert / status change writes one append-only parcel_events row.
-- Never stores carrier signature links (format makes URLs impossible in tracking_ref; carrier rejects URLs).

BEGIN;

SET LOCAL lock_timeout = '5s';        -- never queue behind live order traffic; fail fast and retry later
SET LOCAL statement_timeout = '60s';

-- ─── Preflight (read-only assertions; abort on any surprise) ───────────────────────────────────────────
DO $preflight$
BEGIN
  IF to_regclass('public.orders') IS NULL OR to_regclass('public.branches') IS NULL THEN
    RAISE EXCEPTION 'parcel_01 preflight: public.orders / public.branches missing';
  END IF;
  IF (SELECT data_type FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = 'orders' AND column_name = 'id') IS DISTINCT FROM 'uuid'
  OR (SELECT data_type FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = 'orders' AND column_name = 'branch_id') IS DISTINCT FROM 'uuid'
  OR (SELECT data_type FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = 'branches' AND column_name = 'id') IS DISTINCT FROM 'uuid'
  THEN
    RAISE EXCEPTION 'parcel_01 preflight: orders.id / orders.branch_id / branches.id are not all uuid';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema = 'public' AND table_name = 'orders' AND column_name = 'type')
  OR NOT EXISTS (SELECT 1 FROM information_schema.columns
                  WHERE table_schema = 'public' AND table_name = 'orders' AND column_name = 'status')
  THEN
    RAISE EXCEPTION 'parcel_01 preflight: orders.type / orders.status missing';
  END IF;
  IF to_regclass('public.parcel_requests') IS NOT NULL OR to_regclass('public.parcel_events') IS NOT NULL THEN
    RAISE EXCEPTION 'parcel_01 preflight: parcel tables already exist (no silent re-apply)';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
                  WHERE n.nspname = 'pg_catalog' AND p.proname = 'gen_random_uuid') THEN
    RAISE EXCEPTION 'parcel_01 preflight: pg_catalog.gen_random_uuid() not available';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    RAISE EXCEPTION 'parcel_01 preflight: role service_role missing';
  END IF;
END
$preflight$;

-- ─── parcel_requests ───────────────────────────────────────────────────────────────────────────────────
CREATE TABLE public.parcel_requests (
  id                    uuid        PRIMARY KEY DEFAULT pg_catalog.gen_random_uuid(),
  order_id              uuid        NOT NULL,
  branch_id             uuid        NOT NULL,          -- copied from the saved order by the BEFORE INSERT trigger
  tracking_ref          text        NOT NULL,          -- as entered (staff display only; never in public responses)
  tracking_key          text        GENERATED ALWAYS AS (upper(regexp_replace(tracking_ref, '[^A-Za-z0-9]', '', 'g'))) STORED,
  carrier               text        NULL,              -- optional free text
  status                text        NOT NULL DEFAULT 'awaiting_search',
  close_reason          text        NULL,              -- set only with status 'cancelled'
  last_actor            text        NOT NULL DEFAULT 'system', -- who made the last change (copied into parcel_events)
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  found_at              timestamptz NULL,
  not_found_at          timestamptz NULL,
  handed_to_courier_at  timestamptz NULL,
  carrier_verified_at   timestamptz NULL,
  closed_at             timestamptz NULL,

  CONSTRAINT parcel_requests_order_uq UNIQUE (order_id),
  CONSTRAINT parcel_requests_order_fk FOREIGN KEY (order_id)
    REFERENCES public.orders (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT parcel_requests_branch_fk FOREIGN KEY (branch_id)
    REFERENCES public.branches (id) ON UPDATE RESTRICT ON DELETE RESTRICT,

  -- tracking reference: ASCII only, single spaces, trimmed, 4–40 chars (':' impossible → no URLs)
  CONSTRAINT parcel_requests_tracking_ref_format CHECK (
    tracking_ref ~ '^[A-Za-z0-9 ._/#-]{4,40}$'
    AND tracking_ref = btrim(tracking_ref)
    AND tracking_ref !~ '  '
  ),
  CONSTRAINT parcel_requests_tracking_key_len CHECK (char_length(tracking_key) BETWEEN 4 AND 40),
  CONSTRAINT parcel_requests_carrier_format CHECK (
    carrier IS NULL OR (
      char_length(carrier) BETWEEN 1 AND 40
      AND carrier = btrim(carrier)
      AND carrier !~ '[[:cntrl:]]'
      AND carrier !~* '(https?:|www\.|//)'
    )
  ),
  CONSTRAINT parcel_requests_status_check CHECK (status IN (
    'awaiting_search', 'found', 'not_found', 'handed_to_courier',
    'carrier_verified', 'delivery_problem', 'returned_to_store', 'cancelled'
  )),
  CONSTRAINT parcel_requests_close_reason_check CHECK (
    close_reason IS NULL OR close_reason IN ('order_cancelled', 'food_only', 'customer_request', 'duplicate', 'other')
  ),
  CONSTRAINT parcel_requests_close_reason_iff_cancelled CHECK ((status = 'cancelled') = (close_reason IS NOT NULL)),
  CONSTRAINT parcel_requests_last_actor_format CHECK (last_actor ~ '^[a-z0-9_:-]{2,64}$'),

  -- operational timestamps consistent with the current status (stamped by the BEFORE trigger)
  CONSTRAINT parcel_requests_found_ts CHECK (status <> 'found' OR found_at IS NOT NULL),
  CONSTRAINT parcel_requests_not_found_ts CHECK (status <> 'not_found' OR not_found_at IS NOT NULL),
  CONSTRAINT parcel_requests_handoff_ts CHECK (
    status NOT IN ('handed_to_courier', 'delivery_problem', 'returned_to_store', 'carrier_verified')
    OR handed_to_courier_at IS NOT NULL
  ),
  CONSTRAINT parcel_requests_verified_ts CHECK (status <> 'carrier_verified' OR carrier_verified_at IS NOT NULL),
  CONSTRAINT parcel_requests_closed_ts CHECK (
    (status IN ('carrier_verified', 'returned_to_store', 'cancelled')) = (closed_at IS NOT NULL)
  )
);

COMMENT ON TABLE public.parcel_requests IS
  'Optional parcel attached to a delivery order (parcel module, GATE 03B). Server-only: RLS on, no policies, '
  'service_role grants only. Parcel status is independent of orders.status. Never stores carrier signature links.';
COMMENT ON COLUMN public.parcel_requests.tracking_ref IS
  'Parcel tracking/identification number as entered by the customer. Staff-only; never returned by public APIs or logged.';
COMMENT ON COLUMN public.parcel_requests.tracking_key IS
  'Normalized duplicate-detection key: upper(tracking_ref without non-alphanumerics). Same rule as the application.';

-- Conservative active-duplicate protection: one active request per (branch, normalized number), any carrier.
-- not_found stays active (the parcel may still turn up); carrier_verified / returned_to_store / cancelled release it.
CREATE UNIQUE INDEX parcel_requests_active_key_uq
  ON public.parcel_requests (branch_id, tracking_key)
  WHERE status IN ('awaiting_search', 'found', 'not_found', 'handed_to_courier', 'delivery_problem');

CREATE INDEX parcel_requests_branch_status_idx ON public.parcel_requests (branch_id, status);

-- ─── parcel_events (append-only history) ───────────────────────────────────────────────────────────────
CREATE TABLE public.parcel_events (
  id           uuid        PRIMARY KEY DEFAULT pg_catalog.gen_random_uuid(),
  parcel_id    uuid        NOT NULL,
  order_id     uuid        NOT NULL,
  from_status  text        NULL,          -- NULL for the creation event
  to_status    text        NOT NULL,
  actor        text        NOT NULL,
  occurred_at  timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT parcel_events_parcel_fk FOREIGN KEY (parcel_id)
    REFERENCES public.parcel_requests (id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT parcel_events_status_check CHECK (
    to_status IN ('awaiting_search', 'found', 'not_found', 'handed_to_courier',
                  'carrier_verified', 'delivery_problem', 'returned_to_store', 'cancelled')
    AND (from_status IS NULL OR from_status IN ('awaiting_search', 'found', 'not_found', 'handed_to_courier',
                                                'carrier_verified', 'delivery_problem', 'returned_to_store', 'cancelled'))
  ),
  CONSTRAINT parcel_events_actor_format CHECK (actor ~ '^[a-z0-9_:-]{2,64}$')
);

COMMENT ON TABLE public.parcel_events IS
  'Append-only parcel status history (written only by the parcel_requests trigger). Server-only.';

CREATE INDEX parcel_events_parcel_idx ON public.parcel_events (parcel_id, occurred_at);

-- ─── Trigger: validate + stamp parcel_requests writes ──────────────────────────────────────────────────
-- Concurrency: this trigger READS public.orders without locking. The optional orders gate (parcel_03) locks
-- orders first and then the parcel row (FOR SHARE); this trigger runs while the parcel row is already locked
-- by the UPDATE and never locks orders → no lock-order cycle between the two paths.
CREATE FUNCTION public.parcel_requests_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $fn$
DECLARE
  v_order_type   text;
  v_order_status text;
  v_order_branch uuid;
  v_search       boolean;
BEGIN
  SELECT o.type, o.status, o.branch_id
    INTO v_order_type, v_order_status, v_order_branch
    FROM public.orders AS o
   WHERE o.id = NEW.order_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'parcel_order_not_found' USING ERRCODE = '23503';
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF v_order_type IS DISTINCT FROM 'delivery' THEN
      RAISE EXCEPTION 'parcel_requires_delivery_order' USING ERRCODE = '22023';
    END IF;
    IF v_order_status IS DISTINCT FROM 'received' THEN
      RAISE EXCEPTION 'parcel_order_not_received' USING ERRCODE = '22023';
    END IF;
    IF v_order_branch IS NULL THEN
      RAISE EXCEPTION 'parcel_order_without_branch' USING ERRCODE = '22023';
    END IF;
    IF NEW.status IS DISTINCT FROM 'awaiting_search' OR NEW.close_reason IS NOT NULL THEN
      RAISE EXCEPTION 'parcel_invalid_initial_state' USING ERRCODE = '22023';
    END IF;

    NEW.branch_id            := v_order_branch;   -- always the saved order's branch
    NEW.created_at           := now();
    NEW.updated_at           := now();
    NEW.found_at             := NULL;
    NEW.not_found_at         := NULL;
    NEW.handed_to_courier_at := NULL;
    NEW.carrier_verified_at  := NULL;
    NEW.closed_at            := NULL;
    RETURN NEW;
  END IF;

  -- UPDATE: identity / tracking columns are immutable
  IF NEW.id IS DISTINCT FROM OLD.id
     OR NEW.order_id IS DISTINCT FROM OLD.order_id
     OR NEW.branch_id IS DISTINCT FROM OLD.branch_id
     OR NEW.tracking_ref IS DISTINCT FROM OLD.tracking_ref
     OR NEW.carrier IS DISTINCT FROM OLD.carrier
     OR NEW.created_at IS DISTINCT FROM OLD.created_at
  THEN
    RAISE EXCEPTION 'parcel_immutable_column' USING ERRCODE = '22023';
  END IF;

  IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RAISE EXCEPTION 'parcel_no_status_change' USING ERRCODE = '22023';
  END IF;

  -- Allowed parcel transitions
  IF NOT CASE OLD.status
           WHEN 'awaiting_search'   THEN NEW.status IN ('found', 'not_found', 'cancelled')
           WHEN 'not_found'         THEN NEW.status IN ('found', 'cancelled')
           WHEN 'found'             THEN NEW.status IN ('awaiting_search', 'handed_to_courier', 'cancelled')
           WHEN 'handed_to_courier' THEN NEW.status IN ('carrier_verified', 'delivery_problem', 'returned_to_store')
           WHEN 'delivery_problem'  THEN NEW.status IN ('carrier_verified', 'returned_to_store')
           ELSE false                -- carrier_verified, returned_to_store, cancelled are terminal
         END
  THEN
    RAISE EXCEPTION 'parcel_invalid_transition' USING ERRCODE = '22023';
  END IF;

  -- Order-state conditions
  v_search := NEW.status IN ('found', 'not_found', 'awaiting_search');
  IF v_search AND v_order_status IS DISTINCT FROM 'received' THEN
    RAISE EXCEPTION 'parcel_search_requires_received_order' USING ERRCODE = '22023';
  END IF;

  IF NEW.status = 'handed_to_courier'
     AND NOT coalesce(v_order_status IN ('confirmed', 'preparing', 'ready', 'delivered'), false) THEN
    RAISE EXCEPTION 'parcel_handoff_requires_accepted_order' USING ERRCODE = '22023';
  END IF;

  IF NEW.status = 'cancelled' THEN
    IF NEW.close_reason IS NULL THEN
      RAISE EXCEPTION 'parcel_cancel_requires_reason' USING ERRCODE = '22023';
    END IF;
    IF NEW.close_reason = 'order_cancelled' AND v_order_status IS DISTINCT FROM 'cancelled' THEN
      RAISE EXCEPTION 'parcel_order_not_cancelled' USING ERRCODE = '22023';
    END IF;
    -- "food only" (agreed not-found workflow): only from not_found, before the order is accepted
    IF NEW.close_reason = 'food_only'
       AND (OLD.status IS DISTINCT FROM 'not_found' OR v_order_status IS DISTINCT FROM 'received') THEN
      RAISE EXCEPTION 'parcel_food_only_requires_not_found' USING ERRCODE = '22023';
    END IF;
    IF NEW.close_reason IN ('customer_request', 'duplicate', 'other')
       AND v_order_status IS DISTINCT FROM 'received' THEN
      RAISE EXCEPTION 'parcel_cancel_requires_received_order' USING ERRCODE = '22023';
    END IF;
  ELSIF NEW.close_reason IS NOT NULL THEN
    RAISE EXCEPTION 'parcel_close_reason_without_cancel' USING ERRCODE = '22023';
  END IF;

  -- Database-stamped operational timestamps
  NEW.updated_at := now();
  IF NEW.status = 'found' THEN
    NEW.found_at := now();
  ELSIF NEW.status = 'not_found' THEN
    NEW.not_found_at := now();
  ELSIF NEW.status = 'awaiting_search' THEN   -- correction of a mistaken "found"
    NEW.found_at := NULL;
  ELSIF NEW.status = 'handed_to_courier' THEN
    NEW.handed_to_courier_at := now();
  ELSIF NEW.status = 'carrier_verified' THEN
    NEW.carrier_verified_at := now();
  END IF;
  IF NEW.status IN ('carrier_verified', 'returned_to_store', 'cancelled') THEN
    NEW.closed_at := now();
  END IF;

  RETURN NEW;
END
$fn$;

CREATE TRIGGER parcel_requests_before_write
  BEFORE INSERT OR UPDATE ON public.parcel_requests
  FOR EACH ROW EXECUTE FUNCTION public.parcel_requests_before_write();

-- ─── Trigger: append one history row per creation / status change ──────────────────────────────────────
CREATE FUNCTION public.parcel_requests_log_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $fn$
BEGIN
  INSERT INTO public.parcel_events (parcel_id, order_id, from_status, to_status, actor)
  VALUES (
    NEW.id,
    NEW.order_id,
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE OLD.status END,
    NEW.status,
    NEW.last_actor
  );
  RETURN NULL;   -- AFTER trigger
END
$fn$;

CREATE TRIGGER parcel_requests_log_insert
  AFTER INSERT ON public.parcel_requests
  FOR EACH ROW EXECUTE FUNCTION public.parcel_requests_log_event();

CREATE TRIGGER parcel_requests_log_status
  AFTER UPDATE OF status ON public.parcel_requests
  FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
  EXECUTE FUNCTION public.parcel_requests_log_event();

